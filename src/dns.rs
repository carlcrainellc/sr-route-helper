//! Pointing the system's DNS at the router while a full tunnel is up.
//!
//! With systemd-resolved the tunnel link gets the router as its DNS server, the `~.`
//! routing domain (all lookups) and the DNS default route. The router's DNS listener for
//! this is the one on 127.0.0.1 (a random port on systemd builds): resolved 249 and later
//! sends a link's queries out of that link and only special-cases 127.0.0.1, so 127.3.2.1
//! on a tunnel link doesn't get answers (lokinet issue #1887). Without resolved,
//! `/etc/resolv.conf` is rewritten to the router's 127.3.2.1 listener and the original is
//! kept in the journal. NetworkManager, resolvconf or a DHCP client rewriting the file
//! while we're up is noticed and undone; their newer file is what comes back afterwards.

use crate::journal::DnsChange;
use std::collections::HashSet;
use std::fs;
use std::io;
use std::net::Ipv4Addr;
use std::path::Path;
use std::process::Command;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Auto,
    Resolved,
    ResolvConf,
    Off,
}

impl std::str::FromStr for Mode {
    type Err = String;
    fn from_str(s: &str) -> Result<Mode, String> {
        Ok(match s {
            "auto" => Mode::Auto,
            "resolved" => Mode::Resolved,
            "resolv-conf" => Mode::ResolvConf,
            "off" => Mode::Off,
            _ => {
                return Err(format!(
                    "unknown DNS mode {s:?} (auto, resolved, resolv-conf, off)"
                ));
            }
        })
    }
}

/// Picks resolved when it is the system resolver (resolv.conf points at its stub) and
/// `resolvectl` works; otherwise resolv.conf. The second value says who else manages the
/// file, for the log.
pub fn detect(resolv_conf: &Path) -> (Mode, Option<&'static str>) {
    let link = fs::read_link(resolv_conf)
        .map(|t| t.to_string_lossy().into_owned())
        .unwrap_or_default();
    let text = fs::read_to_string(resolv_conf).unwrap_or_default();
    let stub = link.contains("systemd/resolve") || text.contains("nameserver 127.0.0.53");
    if stub && resolvectl(&["status", "--no-pager"]).is_ok() {
        return (Mode::Resolved, None);
    }
    let who = if text.contains("Generated by NetworkManager") {
        Some("NetworkManager")
    } else if link.contains("resolvconf") || text.contains("resolvconf") {
        Some("resolvconf")
    } else {
        None
    };
    (Mode::ResolvConf, who)
}

fn resolvectl(args: &[&str]) -> io::Result<String> {
    let out = Command::new("resolvectl").args(args).output()?;
    if !out.status.success() {
        return Err(io::Error::other(format!(
            "resolvectl {}: {}",
            args.join(" "),
            String::from_utf8_lossy(&out.stderr).trim()
        )));
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// The text we put in resolv.conf.
pub fn resolv_conf_text(dns: &str) -> String {
    format!(
        "# Written by sr-route-helper while a Session Router exit is mapped.\n# The previous file comes back when the exit is unmapped or the helper stops.\nnameserver {dns}\n"
    )
}

/// Where and how DNS should be pointed at the router.
pub struct Target<'a> {
    pub mode: Mode,
    pub resolv_conf: &'a Path,
    pub tun_name: &'a str,
    pub tun_index: u32,
    /// The router's listener for resolv.conf (default 127.3.2.1).
    pub dns: &'a str,
    /// `--resolved-dns`: the server to give resolved, instead of looking for the router's
    /// 127.0.0.1 listener.
    pub resolved_dns: Option<&'a str>,
    /// Process name of the router, for finding its 127.0.0.1 listener.
    pub router_comm: &'a str,
}

/// Works out the change to make and returns it, so the caller can journal it *before*
/// calling [`apply`]. The `String` is a warning for the log, if any.
pub fn prepare(t: &Target) -> io::Result<(Option<DnsChange>, Option<String>)> {
    match t.mode {
        Mode::Off | Mode::Auto => Ok((None, None)),
        Mode::ResolvConf => Ok((
            Some(DnsChange::ResolvConf {
                path: t.resolv_conf.display().to_string(),
                original: fs::read_to_string(t.resolv_conf).unwrap_or_default(),
                ours: resolv_conf_text(t.dns),
            }),
            None,
        )),
        Mode::Resolved => {
            let (server, warn) = match t.resolved_dns {
                Some(s) => (s.to_owned(), None),
                None => match find_router_listener(t.router_comm) {
                    Some((ip, port)) => (format!("{ip}:{port}"), None),
                    None => (
                        t.dns.to_owned(),
                        Some(format!(
                            "can't find the router's 127.0.0.1 DNS listener; giving resolved {} \
                             instead, which resolved 249+ may not answer on a tunnel link. \
                             Set [dns] listen=127.0.0.1:953 in the router and pass \
                             --resolved-dns 127.0.0.1:953",
                            t.dns
                        )),
                    ),
                },
            };
            let link = t.tun_name;
            let prev_dns = resolvectl(&["dns", link])
                .map(|s| link_values(&s, link))
                .unwrap_or_default();
            let prev_domains = resolvectl(&["domain", link])
                .map(|s| link_values(&s, link))
                .unwrap_or_default();
            let prev_default_route = resolvectl(&["default-route", link])
                .ok()
                .and_then(|s| link_values(&s, link).first().map(|v| v == "yes"));
            Ok((
                Some(DnsChange::Resolved {
                    link: link.into(),
                    ifindex: t.tun_index,
                    server,
                    prev_dns,
                    prev_domains,
                    prev_default_route,
                    muted: vec![],
                }),
                warn,
            ))
        }
    }
}

pub fn apply(c: &DnsChange) -> io::Result<()> {
    match c {
        DnsChange::ResolvConf { path, ours, .. } => write_file(Path::new(path), ours),
        DnsChange::Resolved { link, server, .. } => {
            resolvectl(&["dns", link, server])?;
            resolvectl(&["domain", link, "~."])?;
            resolvectl(&["default-route", link, "yes"]).map(|_| ())
        }
    }
}

/// Puts things back. A resolv.conf somebody else rewrote since is theirs now and stays;
/// a tunnel link that is gone took its resolved settings with it.
pub fn undo(c: &DnsChange) -> io::Result<()> {
    match c {
        DnsChange::ResolvConf {
            path,
            original,
            ours,
        } => {
            let now = fs::read_to_string(path).unwrap_or_default();
            if now == *ours {
                write_file(Path::new(path), original)?;
            }
            Ok(())
        }
        DnsChange::Resolved {
            link,
            prev_dns,
            prev_domains,
            prev_default_route,
            muted,
            ..
        } => {
            unmute(muted);
            if !Path::new("/sys/class/net").join(link).exists() {
                return Ok(());
            }
            let mut args = vec!["dns", link.as_str()];
            if prev_dns.is_empty() {
                args.push("");
            } else {
                args.extend(prev_dns.iter().map(String::as_str));
            }
            resolvectl(&args)?;
            let mut args = vec!["domain", link.as_str()];
            if prev_domains.is_empty() {
                args.push("");
            } else {
                args.extend(prev_domains.iter().map(String::as_str));
            }
            resolvectl(&args)?;
            let dr = if prev_default_route.unwrap_or(false) {
                "yes"
            } else {
                "no"
            };
            resolvectl(&["default-route", link, dr]).map(|_| ())
        }
    }
}

/// resolv.conf mode: if something else rewrote the file while we're up, take their
/// version as the one to put back later and point the file at the router again.
/// Returns true when it changed `c` (the caller journals it).
pub fn reassert(c: &mut DnsChange) -> io::Result<bool> {
    if let DnsChange::ResolvConf {
        path,
        original,
        ours,
    } = c
    {
        let now = fs::read_to_string(&*path).unwrap_or_default();
        if now != *ours {
            *original = now;
            write_file(Path::new(path), ours)?;
            return Ok(true);
        }
    }
    Ok(false)
}

/// resolved mode, tunnel gone while failing closed: the links resolved would now send
/// every lookup to (the uplinks, with DNS default route on), other than the tunnel.
pub fn links_to_mute(tun_name: &str) -> Vec<String> {
    resolvectl(&["default-route"])
        .map(|s| {
            all_links(&s)
                .into_iter()
                .filter(|(name, v)| name != tun_name && v.first().is_some_and(|v| v == "yes"))
                .map(|(name, _)| name)
                .collect()
        })
        .unwrap_or_default()
}

/// Turns off the DNS default route on one link, so resolved has nowhere to send lookups
/// that the router would have answered.
pub fn mute(link: &str) -> io::Result<()> {
    resolvectl(&["default-route", link, "no"]).map(|_| ())
}

fn unmute(links: &[String]) {
    for l in links {
        if Path::new("/sys/class/net").join(l).exists() {
            let _ = resolvectl(&["default-route", l, "yes"]);
        }
    }
}

/// Writes in place (not by rename) so a bind-mounted or symlinked resolv.conf keeps
/// pointing where it did.
fn write_file(path: &Path, text: &str) -> io::Result<()> {
    fs::write(path, text)
}

/// Every `Link N (name): values` line of resolvectl's output.
fn all_links(s: &str) -> Vec<(String, Vec<String>)> {
    s.lines()
        .filter_map(|l| {
            let rest = l.trim_start().strip_prefix("Link ")?;
            let open = rest.find('(')?;
            let (name, vals) = rest[open + 1..].split_once("):")?;
            Some((
                name.to_owned(),
                vals.split_whitespace().map(str::to_owned).collect(),
            ))
        })
        .collect()
}

/// The values on the line for `link` (`Link 7 (sr-tun0): ~sesh ~snode` -> those two).
fn link_values(s: &str, link: &str) -> Vec<String> {
    all_links(s)
        .into_iter()
        .find(|(n, _)| n == link)
        .map(|(_, v)| v)
        .unwrap_or_default()
}

/// One row of /proc/net/udp: local address, port, uid, inode.
type UdpRow = (Ipv4Addr, u16, u32, u64);

fn parse_proc_udp(text: &str) -> Vec<UdpRow> {
    text.lines()
        .skip(1)
        .filter_map(|l| {
            let f: Vec<&str> = l.split_whitespace().collect();
            let (a, p) = f.get(1)?.split_once(':')?;
            // The address is the in-memory (network order) value printed as a native u32.
            let raw = u32::from_str_radix(a, 16).ok()?;
            let ip = Ipv4Addr::from(raw.to_ne_bytes());
            let port = u16::from_str_radix(p, 16).ok()?;
            let uid = f.get(7)?.parse().ok()?;
            let inode = f.get(9)?.parse().ok()?;
            Some((ip, port, uid, inode))
        })
        .collect()
}

/// The router's UDP listener on 127.0.0.1: a socket the router owns (by inode, when we
/// may look at its file descriptors), or failing that the only one owned by its user.
fn choose_listener(
    rows: &[UdpRow],
    inodes: &HashSet<u64>,
    uids: &HashSet<u32>,
) -> Option<(Ipv4Addr, u16)> {
    let lo: Vec<&UdpRow> = rows
        .iter()
        .filter(|r| r.0 == Ipv4Addr::LOCALHOST && r.1 != 0)
        .collect();
    let mut by_inode: Vec<&UdpRow> = lo
        .iter()
        .copied()
        .filter(|r| inodes.contains(&r.3))
        .collect();
    by_inode.sort_by_key(|r| r.1);
    if let Some(r) = by_inode.first() {
        return Some((r.0, r.1));
    }
    let by_uid: Vec<&UdpRow> = lo.into_iter().filter(|r| uids.contains(&r.2)).collect();
    match by_uid.as_slice() {
        [r] => Some((r.0, r.1)),
        _ => None,
    }
}

fn find_router_listener(comm: &str) -> Option<(Ipv4Addr, u16)> {
    let mut inodes = HashSet::new();
    let mut uids = HashSet::new();
    for e in fs::read_dir("/proc").ok()?.flatten() {
        let p = e.path();
        if !fs::read_to_string(p.join("comm")).is_ok_and(|c| c.trim() == comm) {
            continue;
        }
        if let Some(uid) = fs::read_to_string(p.join("status")).ok().and_then(|s| {
            s.lines()
                .find_map(|l| l.strip_prefix("Uid:"))
                .and_then(|v| v.split_whitespace().next()?.parse().ok())
        }) {
            uids.insert(uid);
        }
        if let Ok(fds) = fs::read_dir(p.join("fd")) {
            for fd in fds.flatten() {
                if let Ok(t) = fs::read_link(fd.path()) {
                    let t = t.to_string_lossy();
                    if let Some(n) = t.strip_prefix("socket:[").and_then(|r| r.strip_suffix(']')) {
                        if let Ok(n) = n.parse() {
                            inodes.insert(n);
                        }
                    }
                }
            }
        }
    }
    if uids.is_empty() {
        return None;
    }
    let rows = parse_proc_udp(&fs::read_to_string("/proc/net/udp").ok()?);
    choose_listener(&rows, &inodes, &uids)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_resolvectl_lines() {
        let out = "Global:\nLink 2 (eth0): 192.168.1.1\nLink 7 (sr-tun0): ~sesh ~snode ~loki\n";
        assert_eq!(
            link_values(out, "sr-tun0"),
            vec!["~sesh", "~snode", "~loki"]
        );
        assert_eq!(link_values(out, "eth0"), vec!["192.168.1.1"]);
        assert!(link_values(out, "wlan0").is_empty());
        assert!(link_values("Link 7 (sr-tun0):\n", "sr-tun0").is_empty());
        assert_eq!(
            all_links("Link 2 (eth0): yes\nLink 3 (wlp0s20f3): no\nLink 7 (sr-tun0): yes\n"),
            vec![
                ("eth0".to_string(), vec!["yes".to_string()]),
                ("wlp0s20f3".to_string(), vec!["no".to_string()]),
                ("sr-tun0".to_string(), vec!["yes".to_string()]),
            ]
        );
    }

    #[test]
    fn resolv_conf_round_trip_and_hands_off() {
        let p = std::env::temp_dir().join(format!("srrh-resolv-{}", std::process::id()));
        fs::write(&p, "nameserver 192.168.1.1\n").unwrap();
        let t = Target {
            mode: Mode::ResolvConf,
            resolv_conf: &p,
            tun_name: "sr-tun0",
            tun_index: 9,
            dns: "127.3.2.1",
            resolved_dns: None,
            router_comm: "session-router",
        };
        let mut c = prepare(&t).unwrap().0.unwrap();
        apply(&c).unwrap();
        assert!(fs::read_to_string(&p)
            .unwrap()
            .contains("nameserver 127.3.2.1"));
        assert!(!reassert(&mut c).unwrap());
        undo(&c).unwrap();
        assert_eq!(fs::read_to_string(&p).unwrap(), "nameserver 192.168.1.1\n");
        // Somebody else (DHCP) rewrote it while we were up: leave theirs.
        apply(&c).unwrap();
        fs::write(&p, "nameserver 10.0.0.1\n").unwrap();
        undo(&c).unwrap();
        assert_eq!(fs::read_to_string(&p).unwrap(), "nameserver 10.0.0.1\n");
        // ... or, while still up, point it back at the router and remember theirs.
        apply(&c).unwrap();
        fs::write(&p, "# Generated by NetworkManager\nnameserver 10.0.0.2\n").unwrap();
        assert!(reassert(&mut c).unwrap());
        assert!(fs::read_to_string(&p)
            .unwrap()
            .contains("nameserver 127.3.2.1"));
        undo(&c).unwrap();
        assert_eq!(
            fs::read_to_string(&p).unwrap(),
            "# Generated by NetworkManager\nnameserver 10.0.0.2\n"
        );
        assert_eq!(detect(&p), (Mode::ResolvConf, Some("NetworkManager")));
        let _ = fs::remove_file(p);
    }

    const PROC_UDP: &str = "  sl  local_address rem_address   st tx_queue rx_queue tr tm->when retrnsmt   uid  timeout inode ref pointer drops
  101: 0100007F:0143 00000000:0000 07 00000000:00000000 00:00000000 00000000     0        0 1111 2 0000000000000000 0
  102: 0100007F:E1A4 00000000:0000 07 00000000:00000000 00:00000000 00000000   997        0 2222 2 0000000000000000 0
  103: 0102037F:0035 00000000:0000 07 00000000:00000000 00:00000000 00000000   997        0 3333 2 0000000000000000 0
  104: 00000000:4E21 00000000:0000 07 00000000:00000000 00:00000000 00000000   997        0 4444 2 0000000000000000 0
";

    #[test]
    fn finds_the_router_listener_in_proc_net_udp() {
        let rows = parse_proc_udp(PROC_UDP);
        assert_eq!(rows.len(), 4);
        assert_eq!(rows[0], (Ipv4Addr::LOCALHOST, 323, 0, 1111));
        assert_eq!(rows[2], (Ipv4Addr::new(127, 3, 2, 1), 53, 997, 3333));
        let no_inodes: HashSet<u64> = HashSet::new();
        let no_uids: HashSet<u32> = HashSet::new();
        // By inode when we can see the router's sockets.
        assert_eq!(
            choose_listener(&rows, &HashSet::from([2222, 3333, 4444]), &no_uids),
            Some((Ipv4Addr::LOCALHOST, 0xE1A4))
        );
        // By user otherwise, but only if it's unambiguous (chrony's 127.0.0.1:323 is root's).
        assert_eq!(
            choose_listener(&rows, &no_inodes, &HashSet::from([997])),
            Some((Ipv4Addr::LOCALHOST, 0xE1A4))
        );
        assert_eq!(
            choose_listener(&rows, &no_inodes, &HashSet::from([0, 997])),
            None
        );
        assert_eq!(
            choose_listener(&rows, &no_inodes, &HashSet::from([5])),
            None
        );
    }

    #[test]
    fn mode_names() {
        assert_eq!("resolved".parse::<Mode>().unwrap(), Mode::Resolved);
        assert!("dnsmasq".parse::<Mode>().is_err());
    }
}
